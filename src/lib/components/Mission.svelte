	<h2>Mission</h2>
	<p>
		<i>The Innovator</i>
		is a student-run newspaper at Innovation Academy Charter School in Tyngsborough, Massachusetts committed
		to providing the IACS high school community with accurate, informative and up-to-date stories, and
		a public forum for student expression.&nbsp;
	</p>
	<p>
		<i>The Innovator</i>
		is entirely student-run, and therefore, all decisions are made by students. The editors will often
		seek guidance from the faculty advisor, but all final decisions are made by the Head Editors. Questions,
		comments, or concerns should be directed to
		<a href="mailto:innovator-editor@innovationcharter.org">the Head Editors</a>.
	</p>
</div>
